import 'dart:io';

void main() {
  print('How many numbers?');
  int n = int.parse(stdin.readLineSync()!);

  List<int> numbers = [];

  for (int i = 1; i <= n; i++) {
    print('Enter number:');
    int number = int.parse(stdin.readLineSync()!);
    numbers.add(number);
  }

  print(getSecondSmallest(numbers));
}

int getSecondSmallest(List<int> numbers) {
  numbers.sort();
  return numbers[1];
}